export function buildCoverLetterPrompt({ job, latestReview }) {
  const jobId = job.id;
  const draftDir = `<TRACKER_ROOT>/storage/cover_letter_drafts/job-${jobId}`;
  const textPath = `${draftDir}/cover-letter.txt`;
  const pdfPath = `${draftDir}/cover-letter.pdf`;

  return [
    "You are working inside a local clone of `codex-job-kit`.",
    "",
    "Before you start, replace `<REPO_ROOT>`, `<TRACKER_ROOT>`, and `<CANDIDATE_PROFILE>` with the local paths for this installation.",
    "",
    "Task: generate a tailored cover letter for the role below and register it in the local job tracker.",
    "",
    "Required context sources:",
    "- `<CANDIDATE_PROFILE>`",
    "- any local resume, portfolio, or experience notes explicitly provided by the user",
    "- the job details and tracker assessment below",
    "",
    "Hard rules:",
    "- Do not invent facts.",
    "- Do not overstate experience.",
    "- Write the cover letter as plain text, not Markdown.",
    "- Keep claims evidence-based and consistent with the repo.",
    "",
    "Candidate context:",
    "- Use `<CANDIDATE_PROFILE>` as the source of truth.",
    "- Do not infer authorization, location, availability, salary, education, or years of experience unless they are present in the candidate profile.",
    "",
    "Role details:",
    `- Job ID: ${jobId}`,
    `- Title: ${job.title}`,
    `- Company: ${job.company}`,
    `- Platform: ${job.platform || "Unknown"}`,
    `- Location: ${job.location || "Not listed"}`,
    `- Work mode: ${job.work_mode || "Not listed"}`,
    `- Employment type: ${job.employment_type || "Not listed"}`,
    `- Salary: ${job.salary_text || "Not listed"}`,
    `- Canonical URL: ${job.canonical_url}`,
    `- Role summary: ${job.description_summary || "Not recorded"}`,
    "",
    "Tracker assessment:",
    `- Recommendation bucket: ${latestReview?.bucket || "Not recorded"}`,
    `- Fit assessment: ${latestReview?.fit_assessment || "Not recorded"}`,
    `- Risk note: ${latestReview?.risk_note || "Not recorded"}`,
    `- Legitimacy note: ${latestReview?.legitimacy_note || "Not recorded"}`,
    "",
    "Output workflow:",
    `1. Create the repo-local draft folder \`${draftDir}\` if it does not already exist.`,
    `2. Generate the final cover letter text and save it to \`${textPath}\`.`,
    `3. If you also generate a PDF, save it to \`${pdfPath}\`.`,
    "4. Register the generated files in the tracker by running:",
    "```bash",
    'cd "<TRACKER_ROOT>"',
    `pnpm store-cover-letter --job-id ${jobId} --text-file "${textPath}" --pdf-file "${pdfPath}"`,
    "```",
    "5. If no PDF was created, omit the `--pdf-file` flag and still store the plain-text version.",
    "6. At the end, report the final stored file paths and confirm that the tracker was updated.",
  ].join("\n");
}
